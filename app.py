from datasets import Dataset
from transformers import AutoTokenizer, AutoModelForSequenceClassification, TrainingArguments, Trainer

# 1. Reload the Tokenizer and Foundation Model
model_checkpoint = "xlm-roberta-base"
tokenizer = AutoTokenizer.from_pretrained(model_checkpoint)
model = AutoModelForSequenceClassification.from_pretrained(model_checkpoint, num_labels=2)

# 2. Recreate a quick dummy dataset (assuming you have a 'cleaned_uzbek_data.csv' or similar text list)
# If you don't have the CSV loaded, we will make a tiny 2-sentence dataset just to make the code run
dummy_data = pd.DataFrame({
    "text": ["O'zbekiston iqtisodiyoti o'smoqda.", "Bugun havo juda issiq."],
    "label": [1, 0]
})
hf_dataset = Dataset.from_pandas(dummy_data)

def tokenize_function(examples):
    return tokenizer(examples["text"], padding="max_length", truncation=True, max_length=128)

tokenized_dataset = hf_dataset.map(tokenize_function, batched=True)

# 3. Rebuild the Trainer
training_args = TrainingArguments(
    output_dir="./uzbek_nlp_model",
    num_train_epochs=1, # Just 1 epoch to make it fast for testing
    per_device_train_batch_size=2,
)

trainer = Trainer(
    model=model,
    args=training_args,
    train_dataset=tokenized_dataset,
)

