# 1. Create an empty list to hold all the scraped data
dataset = []

for current_url in urls_to_scrape:
    print(f"Scraping: {current_url}")
    response = requests.get(current_url, headers=headers)

    if response.status_code == 200:
        soup = BeautifulSoup(response.text, 'html.parser')
        paragraphs = soup.find_all('p')

        # Combine the paragraphs into one single block of text
        article_text = ""
        for p in paragraphs[:3]:
            clean_text = p.get_text(strip=True)
            if clean_text:
                article_text += clean_text + " "

        # 2. Add the URL and text into our list as a dictionary
        dataset.append({
            "source": current_url,
            "text": article_text.strip()
        })

    time.sleep(2)

# 3. Create a new file and write the data into it
with open("uzbek_nlp_data.json", "w", encoding="utf-8") as json_file:
    json.dump(dataset, json_file, ensure_ascii=False, indent=4)

print("Scraping complete. Data saved to uzbek_nlp_data.json!")

complex_mapping = {
    "ё": "yo", "Ё": "Yo",
    "ч": "ch", "Ч": "Ch",
    "ш": "sh", "Ш": "Sh",
    "ю": "yu", "Ю": "Yu",
    "я": "ya", "Я": "Ya",
    "ў": "o'", "Ў": "O'",
    "ғ": "g'", "Ғ": "G'"
}

simple_mapping = {
    "а": "a", "б": "b", "в": "v", "г": "g", "д": "d",
    "е": "e", "ж": "j", "з": "z", "и": "i", "й": "y",
    "к": "k", "л": "l", "м": "m", "н": "n", "о": "o",
    "п": "p", "р": "r", "с": "s", "т": "t", "у": "u",
    "ф": "f", "х": "x", "ц": "s", "э": "e", "қ": "q",
    "ҳ": "h"
}

def transliterate_to_latin(text):
    if not isinstance(text, str):
        return text

    for cyrillic, latin in complex_mapping.items():
        text = text.replace(cyrillic, latin)

    for cyrillic, latin in simple_mapping.items():
        text = text.replace(cyrillic, latin)

    return text

# Test it on a sample sentence:
